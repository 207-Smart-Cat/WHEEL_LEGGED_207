//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化矩阵   
// 参数说明    *m 矩阵结构体指针        rows：行数    cols ：列数      
// 返回参数      
//-------------------------------------------------------------------------------------------------------------------
void mat_init(Matrix *m, int rows, int cols)
{
    m->rows = rows;
    m->cols = cols;
    for(int i=0; i<rows; i++)
        for(int j=0; j<cols; j++)
            m->data[i][j] = 0.0f;
}


 //-------------------------------------------------------------------------------------------------------------------
// 函数简介   给矩阵指定位置 (row, col) 赋值 val      
//-------------------------------------------------------------------------------------------------------------------
void mat_set(Matrix *m, int row, int col, float val)
{
    // 简单越界保护
    if(row >= 0 && row < m->rows && col >=0 && col < m->cols)
    {
        m->data[row][col] = val;
    }
}


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     单位矩阵        
//-------------------------------------------------------------------------------------------------------------------

void mat_eye(Matrix *m)
{
    for(int i=0; i<m->rows; i++)
        for(int j=0; j<m->cols; j++)
            m->data[i][j] = (i==j) ? 1.0f : 0.0f;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     矩阵加法 C = A + B        
//-------------------------------------------------------------------------------------------------------------------
void mat_add(Matrix *C, Matrix *A, Matrix *B)
{
    // 校验维度匹配：A/B行列数必须一致，且C的维度与A/B一致
    if(A->rows != B->rows || A->cols != B->cols || 
       C->rows != A->rows || C->cols != A->cols) {
        return; // 维度不匹配，直接返回
    }
    
    for(int i=0; i<A->rows; i++)
        for(int j=0; j<A->cols; j++)
            C->data[i][j] = A->data[i][j] + B->data[i][j];
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     矩阵乘法 C = A * B        
//-------------------------------------------------------------------------------------------------------------------

void mat_mul(Matrix *C, Matrix *A, Matrix *B)
{
    // 校验维度匹配：A的列数=B的行数，且C的行数=A的行数、C的列数=B的列数
    if(A->cols != B->rows || 
       C->rows != A->rows || C->cols != B->cols) {
        return; // 维度不匹配，直接返回
    }
    
    for(int i=0; i<A->rows; i++)
    {
        for(int j=0; j<B->cols; j++)
        {
            float sum = 0;
            for(int k=0; k<A->cols; k++)
                sum += A->data[i][k] * B->data[k][j];
            C->data[i][j] = sum;
        }
    }
}
