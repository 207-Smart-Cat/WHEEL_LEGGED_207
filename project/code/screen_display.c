static void ui_param_keep_visible(uint8_t selected, uint8_t *top, uint8_t count)
{
    if (count <= UI_PARAM_ROWS)
    {
        *top = 0;
        return;
    }

    if (selected < *top)
    {
        *top = selected;
    }
    else if (selected >= (*top + UI_PARAM_ROWS))
    {
        *top = (uint8_t)(selected - UI_PARAM_ROWS + 1);
    }
}


static uint8_t ui_move_index(uint8_t current, uint8_t count, uint8_t step, uint8_t move_down)
{
    if (count <= 1)
    {
        return 0;
    }
    if (step == 0)
    {
        step = 1;
    }
    if (step >= count)
    {
        step = 1;
    }

    if (move_down)
    {
        return (uint8_t)((current + step) % count);
    }
    if (current >= step)
    {
        return (uint8_t)(current - step);
    }
    return (uint8_t)(count - (step - current));
}

