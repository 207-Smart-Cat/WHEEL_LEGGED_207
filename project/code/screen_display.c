static uint8_t ui_key_raw(ui_key_id_t key)
{
    switch (key)
    {
        case UI_KEY_UP:   return gpio_get_level(UI_KEY_UP_PIN);
        case UI_KEY_DOWN: return gpio_get_level(UI_KEY_DOWN_PIN);
        case UI_KEY_OK:   return gpio_get_level(UI_KEY_OK_PIN);
        default:          return gpio_get_level(UI_KEY_BACK_PIN);
    }
}

static void ui_scan_keys(ui_key_event_t events[UI_KEY_COUNT])
{
    for (uint8_t i = 0; i < UI_KEY_COUNT; i++)
    {
        events[i] = UI_EVENT_NONE;
        uint8_t raw = ui_key_raw((ui_key_id_t)i);

        if (raw != ui_keys[i].last_raw_level)
        {
            ui_keys[i].last_raw_level = raw;
            ui_keys[i].debounce_count = 2;
        }
        else if (ui_keys[i].debounce_count > 0)
        {
            ui_keys[i].debounce_count--;
            if (ui_keys[i].debounce_count == 0 && raw != ui_keys[i].stable_level)
            {
                ui_keys[i].stable_level = raw;
                if (raw == 0)
                {
                    ui_keys[i].press_ticks = 0;
                    ui_keys[i].long_sent = 0;
                }
                else
                {
                    if (ui_keys[i].long_sent == 0)
                    {
                        events[i] = UI_EVENT_SHORT;
                    }
                    ui_keys[i].press_ticks = 0;
                }
            }
        }

        if (ui_keys[i].stable_level == 0)
        {
            if (ui_keys[i].press_ticks < 60000)
            {
                ui_keys[i].press_ticks++;
            }
            if (ui_keys[i].press_ticks >= UI_LONG_PRESS_TICKS && ui_keys[i].long_sent == 0)
            {
                ui_keys[i].long_sent = 1;
                events[i] = UI_EVENT_LONG;
            }
            else if ((i == UI_KEY_UP || i == UI_KEY_DOWN) && ui_keys[i].long_sent &&
                     ((ui_keys[i].press_ticks - UI_LONG_PRESS_TICKS) % UI_REPEAT_PRESS_TICKS == 0))
            {
                events[i] = UI_EVENT_LONG;
            }
        }
    }
}

static uint8_t ui_handle_emergency_combo(void)
{
    uint8_t combo_down = (ui_keys[UI_KEY_DOWN].stable_level == 0 && ui_keys[UI_KEY_UP].stable_level == 0) ? 1 : 0;

    if (!combo_down)
    {
        ui_emergency_combo_ticks = 0;
        ui_emergency_combo_fired = 0;
        return 0;
    }

    if (ui_emergency_combo_ticks < 60000)
    {
        ui_emergency_combo_ticks++;
    }

    if (ui_emergency_combo_ticks >= UI_EMERGENCY_COMBO_TICKS && !ui_emergency_combo_fired)
    {
        ui_emergency_combo_fired = 1;
        Vehicle_Emergency_Stop(VEHICLE_EVENT_SOURCE_SCREEN);
        ui_set_screen(UI_SCREEN_HOME);
    }

    return 1;
}
