static const uint8_t *ui_find_cn_glyph(uint16_t code)
{
    for (uint32_t i = 0; i < ARRAY_SIZE(k_ui_cn_glyphs); i++)
    {
        if (k_ui_cn_glyphs[i].code == code)
        {
            return k_ui_cn_glyphs[i].data;
        }
    }
    return NULL;
}

static uint16_t ui_show_text(uint16_t x, uint16_t y, const uint16_t *text)
{
    while (*text)
    {
        if (*text < 128)
        {
            if (x > 232)
            {
                break;
            }
            ips200_show_char(x, y, (char)(*text));
            x += 8;
        }
        else
        {
            if (x > 224)
            {
                break;
            }
            const uint8_t *glyph = ui_find_cn_glyph(*text);
            if (glyph != NULL)
            {
                ips200_show_chinese(x, y, 16, glyph, 1, RGB565_WHITE);
            }
            else
            {
                ips200_show_char(x, y, '?');
            }
            x += 16;
        }
        text++;
    }
    return x;
}

static void ui_show_string_safe(uint16_t x, uint16_t y, const char *text)
{
    char safe_text[31];
    uint8_t max_chars;
    uint8_t i = 0;

    if (text == NULL || x >= 240 || y >= 320)
    {
        return;
    }

    max_chars = (uint8_t)((240 - x) / 8);
    if (max_chars == 0)
    {
        return;
    }
    if (max_chars >= sizeof(safe_text))
    {
        max_chars = (uint8_t)(sizeof(safe_text) - 1);
    }

    while (text[i] != '\0' && i < max_chars)
    {
        safe_text[i] = text[i];
        i++;
    }
    safe_text[i] = '\0';
    ips200_show_string(x, y, safe_text);
}

static void ui_show_text_selected(uint16_t x, uint16_t y, uint8_t selected, const uint16_t *text)
{
    ips200_show_char(x, y, selected ? '>' : ' ');
    ui_show_text((uint16_t)(x + 16), y, text);
}

